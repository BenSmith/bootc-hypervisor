# Per-container keys that may appear at *either* nesting depth in a
# [[containers]] entry:
#   [containers.container.environment] / [containers.container.health]   (nested)
#   [containers.environment]           / [containers.health]              (sibling)
# Single-mode TOMLs always nest these under [container], so we normalize the
# multi-container form to match. The generator reads from container["container"]
# only, so callers do not need to care which form the TOML used.
_LIFTED_CONTAINER_KEYS = ("environment", "health")


def normalize_containers(config: dict) -> list[dict]:
    """Return a list of per-container config dicts in a single canonical shape.

    Single-container TOMLs (top-level [container] block plus top-level
    [security], [storage], [devices], [secrets], [resources]) become a
    one-element list with all per-container fields gathered into it.

    Multi-container TOMLs ([[containers]] arrays) keep their per-entry
    structure, but sibling [containers.environment] / [containers.health]
    are lifted into entry["container"]["environment"] / ["health"] so the
    generator and helpers see the same shape regardless of which TOML form
    the user wrote.
    """
    if "containers" in config:
        result = []
        for entry in config["containers"]:
            normalized = dict(entry)
            container = dict(normalized.get("container", {}))
            for key in _LIFTED_CONTAINER_KEYS:
                if key in normalized:
                    container[key] = normalized.pop(key)
            normalized["container"] = container
            result.append(normalized)
        return result

    container = {
        "name": config["workload"]["name"],
        "container": dict(config.get("container", {})),
        "security": dict(config.get("security", {})),
        "storage":  {"volumes": list(config.get("storage", {}).get("volumes", []))},
        "devices":  dict(config.get("devices", {})),
        "secrets":  dict(config.get("secrets", {})),
        "resources": dict(config.get("resources", {})),
    }
    return [container]


# --- Validation ---

def infer_workload_mode(config: dict) -> str:
    """Return 'single', 'pod', or 'bridge'. Validates the value if explicit."""
    mode = config.get("workload", {}).get("mode")
    if mode is not None:
        if mode not in VALID_WORKLOAD_MODES:
            raise ValueError(
                f"Invalid workload.mode {mode!r}; must be one of {VALID_WORKLOAD_MODES}"
            )
        return mode
    return "pod" if "containers" in config else "single"


# --- Container egress policy/credential schema ---
#
# [network.policy] / [network.credential], parsed the same way and for the
# same reason as [[vm.network.policy]] / [[vm.network.credential]] in
# lib/vm.py: shape-tolerant here, with real validation living in a separate
# validate_* function (not yet written -- there is no container inspector to
# validate against yet). Deliberately its own small NamedTuple pair rather
# than reuse of VmPolicyEntry/VmCredential: those are keyed on `[vm.network]`
# specifically, and container topology has no `[vm]` section to key off of.
# Widening them instead would put a substrate branch inside a pair of
# structures whose whole job is to describe one substrate's table.

class ContainerPolicyEntry(NamedTuple):
    """One [[network.policy]] entry, normalised.

    `methods` and `paths` are `None` where the key was absent, not an empty
    tuple -- absent means "any", empty would mean "none". Same convention as
    VmPolicyEntry, for the same reason: collapsing the two would make a
    single-entry host with no `paths` deny everything instead of permitting
    everything.
    """

    host: str
    methods: tuple | None
    paths: tuple | None
    credential: str | None = None


def container_policy_entries(net: dict) -> list[ContainerPolicyEntry]:
    """The [[network.policy]] entries for one container's [network] table,
    normalised, in file order. Shape-tolerant; a future validate function
    owns rejecting malformed entries."""
    entries: list[ContainerPolicyEntry] = []
    raw = net.get("policy", [])
    if not isinstance(raw, list):
        return entries
    for item in raw:
        if not isinstance(item, dict):
            continue
        host = item.get("host")
        if not isinstance(host, str) or not host.strip():
            continue
        credential = item.get("credential")
        if not isinstance(credential, str) or not credential.strip():
            credential = None
        else:
            credential = credential.strip()
        entries.append(ContainerPolicyEntry(
            host=host.strip(),
            methods=_normalise_container_policy_list(item.get("methods"), upper=True),
            paths=_normalise_container_policy_list(item.get("paths")),
            credential=credential))
    return entries


class ContainerCredential(NamedTuple):
    """One [[network.credential]] block, normalised. Same shape as
    VmCredential (lib/vm.py) and for the same reasons -- see that class's
    docstring for why `auth_header`/`auth_format` are optional and live here
    rather than on the policy entry."""

    name: str
    placeholder: str
    env: str
    auth_header: str | None = None
    auth_format: str | None = None


def container_credential_entries(net: dict) -> list[ContainerCredential]:
    """The [[network.credential]] blocks for one container's [network]
    table, normalised, in file order. Shape-tolerant; a future validate
    function owns rejecting malformed entries."""
    creds: list[ContainerCredential] = []
    raw = net.get("credential", [])
    if not isinstance(raw, list):
        return creds
    for item in raw:
        if not isinstance(item, dict):
            continue
        values = []
        for key in ("name", "placeholder", "env"):
            value = item.get(key)
            if not isinstance(value, str) or not value.strip():
                values = []
                break
            values.append(value.strip())
        if not values:
            continue
        optional = []
        for key in ("auth_header", "auth_format"):
            value = item.get(key)
            optional.append(value.strip()
                            if isinstance(value, str) and value.strip()
                            else None)
        creds.append(ContainerCredential(*values, *optional))
    return creds


def _normalise_container_policy_list(value, *, upper: bool = False) -> tuple | None:
    """One `methods` or `paths` value as a tuple, or None where it was
    absent. None and () are different answers; see ContainerPolicyEntry."""
    if value is None:
        return None
    if not isinstance(value, list):
        return ()
    out = []
    for item in value:
        if not isinstance(item, str):
            continue
        out.append(item.upper() if upper else item)
    return tuple(out)


# --- Container [network] scalars ---
#
# Read the same way as VM's vm_allowed_hosts()/net.get("tls")/etc.
# (lib/vm.py) -- no dedicated parse function on that side either. `tls` is
# deliberately returned raw (None when absent), not defaulted here: unlike
# the VM's fixed default, the container's effective tls is *computed* from
# whether any policy entry is present, and that computation belongs to
# validate_container_network(), not to parsing.

def container_allowed_hosts(net: dict) -> list[str]:
    """The [network].hosts allowlist, in file order. Shape-tolerant."""
    hosts = net.get("hosts", [])
    if not isinstance(hosts, list):
        return []
    return [h for h in hosts if isinstance(h, str) and h.strip()]


def container_tls_mode(net: dict) -> str | None:
    """The literal [network].tls value, or None if absent. Not defaulted --
    see module note above."""
    value = net.get("tls")
    return value if isinstance(value, str) and value.strip() else None


def container_tls_reason(net: dict) -> str | None:
    value = net.get("tls_reason")
    return value.strip() if isinstance(value, str) and value.strip() else None


def container_ca_delivery(net: dict) -> str | None:
    value = net.get("ca_delivery")
    return value.strip() if isinstance(value, str) and value.strip() else None


def container_ca_mount_path(net: dict) -> str | None:
    value = net.get("ca_mount_path")
    return value.strip() if isinstance(value, str) and value.strip() else None


# --- Container [[network.allow]] / [[network.internal]] / [[network.splice]] ---
#
# Shape-tolerant, like the policy/credential pair above -- validation is
# validate_container_network()'s job, not parsing's. Unlike VM's
# _host_reason_hosts() (lib/vm.py:1520-1534), `reason` is kept rather than
# discarded: every entry is required to carry a reason, and unlike
# the VM side -- where a malformed entry can never reach this code because
# the boot path already ran validate_vm_network() -- there is no such
# validator yet, so reporting code reading these tuples needs `reason`
# available rather than assumed-valid-elsewhere.

class ContainerAllowEntry(NamedTuple):
    """One [[network.allow]] entry, normalised. `host` and `address` are
    both surfaced raw (unlike VmAllowEntry, which resolves an address into
    an ipaddress object at parse time) -- that split is a validation
    decision (which regex matched, is it resolvable) this function does not
    make."""

    host: str | None
    address: str | None
    port: int | None
    reason: str | None


def container_allow_entries(net: dict) -> list[ContainerAllowEntry]:
    """The [[network.allow]] entries for one container's [network] table,
    normalised, in file order. Shape-tolerant."""
    entries: list[ContainerAllowEntry] = []
    raw = net.get("allow", [])
    if not isinstance(raw, list):
        return entries
    for item in raw:
        if not isinstance(item, dict):
            continue
        host = item.get("host")
        host = host.strip() if isinstance(host, str) and host.strip() else None
        address = item.get("address")
        address = address.strip() if isinstance(address, str) and address.strip() else None
        if host is None and address is None:
            continue
        port = item.get("port")
        port = port if isinstance(port, int) and not isinstance(port, bool) else None
        reason = item.get("reason")
        reason = reason.strip() if isinstance(reason, str) and reason.strip() else None
        entries.append(ContainerAllowEntry(host=host, address=address, port=port, reason=reason))
    return entries


def container_uses_inspect(config: dict) -> bool:
    """Whether this workload's egress is redirected into an inspector.

    Mirrors ``vm_uses_inspect()`` (lib/vm.py) for the container substrate: the
    single source of the predicate (D2 in the container egress-parity build
    spec). ``ContainerSubstrate.uses_inspect()`` delegates here rather than
    restating the logic, and ``get_enabled_workloads()``
    (libexec/workload-exporter) calls it directly on the raw parsed TOML --
    it reads config off disk and cannot build a WorkloadConfig/Substrate.
    """
    net = config.get("network", {})
    if not isinstance(net, dict):
        return False
    if net.get("mode") == "host":
        # Host-mode shares the host netns entirely, so uid would be the ONLY
        # thing separating this workload's traffic from the host's own --
        # whether the redirect and `meta skuid` still isolate it there is an
        # open spike (P0-1 in the build spec), not yet confirmed on hardware.
        # Never claim inspection this cannot yet prove it provides.
        return False
    # Any one of the three opt-in triggers, not policy alone: `hosts` and
    # `allow` are each triggers on their own (a hosts-only workload gets a
    # spliced proxy with no policy to speak of).
    return bool(container_allowed_hosts(net) or container_policy_entries(net)
                or container_allow_entries(net))


class ContainerHostReasonEntry(NamedTuple):
    """One [[network.internal]] or [[network.splice]] entry, normalised.
    Both arrays share this `{host, reason}` shape, same as the VM side's
    shared `_host_reason_hosts()` helper."""

    host: str
    reason: str | None


def container_internal_entries(net: dict) -> list[ContainerHostReasonEntry]:
    return _container_host_reason_entries(net, "internal")


def container_splice_entries(net: dict) -> list[ContainerHostReasonEntry]:
    return _container_host_reason_entries(net, "splice")


def _container_host_reason_entries(net: dict, key: str) -> list[ContainerHostReasonEntry]:
    raw = net.get(key, [])
    if not isinstance(raw, list):
        return []
    entries = []
    for item in raw:
        if not isinstance(item, dict):
            continue
        host = item.get("host")
        if not isinstance(host, str) or not host.strip():
            continue
        reason = item.get("reason")
        reason = reason.strip() if isinstance(reason, str) and reason.strip() else None
        entries.append(ContainerHostReasonEntry(host=host.strip(), reason=reason))
    return entries


# --- Container [network] validation ---
#
# The parse functions above are deliberately shape-tolerant; every semantic
# rule lives here or nowhere. Mirrors validate_vm_network / _validate_egress
# (lib/vm.py) where the two schemas share a rule. Diverges where the container
# schema has no `egress` key (presence of a trigger is the whole statement)
# and no bridge escape hatch. `mode = "host"` is not special-cased here: the
# container topology under which uid attribution might not hold has not yet
# been confirmed on hardware, so this function has nothing to key that check
# on yet.

_CONTAINER_HOST_RE = re.compile(r"^[A-Za-z0-9*?.\[\]!_-]+$")


def _validate_container_host_pattern(pattern) -> list[str]:
    """Validate one hostname pattern (`hosts`, `policy.host`, or an
    `internal`/`splice` entry's `host`). Same shape rules as VM's
    `_validate_proxy_host` (lib/vm.py) -- duplicated rather than imported
    because workload_lib.py cannot import from vm.py at module level (vm.py
    imports this module)."""
    if not isinstance(pattern, str):
        return [f"entries must be strings, got {pattern!r}"]
    text = pattern.strip()
    if not text:
        return ["entries must not be empty"]
    if "://" in text:
        return [f"{pattern!r} looks like a URL -- patterns match the hostname "
                f"only, so drop the scheme"]
    if "/" in text:
        return [f"{pattern!r} contains a path -- patterns match the hostname "
                f"only, so a path never matches"]
    if ":" in text:
        return [f"{pattern!r} contains a port -- hostname policy applies to "
                f"the redirected ports (80 and 443) only; use "
                f"[[network.allow]] for other ports"]
    if text == "*":
        return ["'*' matches every host, which filters nothing but looks "
                "configured -- drop the [network] table entirely to run "
                "unfiltered"]
    if not _CONTAINER_HOST_RE.match(text):
        return [f"{pattern!r} is not a hostname or fnmatch pattern"]
    return []


def _container_patterns_overlap(a: str, b: str) -> bool:
    """Whether two fnmatch host patterns can name a host in common. Same
    approximation as VM's `_patterns_overlap` (lib/vm.py), duplicated for the
    same import-cycle reason as `_validate_container_host_pattern`."""
    a = a.strip().lower().rstrip(".")
    b = b.strip().lower().rstrip(".")
    if not a or not b:
        return False
    return a == b or fnmatch.fnmatchcase(a, b) or fnmatch.fnmatchcase(b, a)


def container_effective_tls_mode(net: dict) -> str:
    """The tls mode actually in force: the literal key if the operator wrote
    one, else computed per the three-rung ladder -- no policy entries means
    splice, any policy entry means inspect. Meaningless on a workload with no
    trigger at all (no proxy exists for it to describe), but harmless to
    compute. Reporting code (doctor/rules/egress) must call this, not read
    `tls` directly, because the literal key may be absent while a proxy is
    still running in one mode or the other."""
    explicit = container_tls_mode(net)
    if explicit is not None:
        return explicit
    return "inspect" if container_policy_entries(net) else "splice"


def validate_container_network(net: dict) -> list[str]:
    """Validate [network] on a container workload. Returns a list of error
    strings. Implements every numbered rule in the container egress-parity
    build spec's validation section except V13 (reserved for a deferred
    [[network.http2]] array) and the mode="host" delta (blocked on a hardware
    spike this function cannot run itself -- see module note above)."""
    # Lazy import: vm.py imports this module, so a top-level import here
    # would be circular (same pattern as workload_run_files() above).
    from vm import (
        VM_POLICY_METHODS, VM_POLICY_METHODS_REFUSED, VM_RESERVED_GUEST_ENV,
        vm_hostname_match,
    )

    errors: list[str] = []
    if not isinstance(net, dict):
        return ["[network] must be a table"]

    raw_hosts = net.get("hosts", [])
    if not isinstance(raw_hosts, list):
        errors.append(
            f"[network].hosts must be an array of hostname patterns, got "
            f"{type(raw_hosts).__name__}")
        raw_hosts = []
    else:
        for pattern in raw_hosts:
            errors.extend(f"[network].hosts: {e}"
                          for e in _validate_container_host_pattern(pattern))
    hosts = [h.strip() for h in raw_hosts if isinstance(h, str) and h.strip()]

    # --- [[network.allow]] -- shape + reason (V14) ---
    raw_allow = net.get("allow", [])
    if not isinstance(raw_allow, list):
        errors.append(
            f"[network].allow must be an array of [[network.allow]] tables, "
            f"got {type(raw_allow).__name__}")
        raw_allow = []
    for item in raw_allow:
        if not isinstance(item, dict):
            errors.append(f"[network].allow entries are tables with `host` "
                          f"or `address`, `port` and `reason`, got {item!r}")
            continue
        host = item.get("host")
        host = host.strip() if isinstance(host, str) and host.strip() else None
        address = item.get("address")
        address = address.strip() if isinstance(address, str) and address.strip() else None
        label = host or address or repr(item)
        if host is None and address is None:
            errors.append(
                f"[network].allow: entry {item!r} has neither `host` nor "
                f"`address`")
            continue
        if host is not None and address is not None:
            errors.append(
                f"[network].allow: {label!r} has both `host` and `address` "
                f"-- an entry names one destination one way")
            continue
        port = item.get("port")
        if not isinstance(port, int) or isinstance(port, bool) or not 1 <= port <= 65535:
            errors.append(
                f"[network].allow: {label!r} `port` must be an integer "
                f"1-65535, got {port!r}")
        elif port in (80, 443):
            # R5/§5: 80 and 443 are redirected into the inspector before this
            # allowlist is ever consulted -- an element here for either would
            # be armed and never matched, reporting a destination as exempt
            # from inspection that is inspected regardless.
            errors.append(
                f"[network].allow: {label!r} names port {port}, which is "
                f"always redirected to this workload's inspector -- "
                f"[[network.allow]] is for non-80/443 destinations only "
                f"(use .hosts or [[network.policy]] for HTTP/HTTPS)")
        if not isinstance(item.get("reason"), str) or not item["reason"].strip():
            errors.append(  # V14
                f"[network].allow: {label!r} has no `reason`; it is a "
                f"bypass of the internal-destination drop and carries one "
                f"like [[network.internal]] does")

    # --- [[network.internal]] / [[network.splice]] -- shape + reason (V14) ---
    def _validate_host_reason_array(key: str, bypass_clause: str) -> list[str]:
        out_hosts: list[str] = []
        out_errors: list[str] = []
        raw = net.get(key, [])
        if not isinstance(raw, list):
            return [], [f"[network].{key} must be an array of "
                        f"[[network.{key}]] tables, got {type(raw).__name__}"]
        for item in raw:
            if not isinstance(item, dict):
                out_errors.append(f"[network].{key} entries are tables with "
                                  f"`host` and `reason`, got {item!r}")
                continue
            if "host" not in item:
                out_errors.append(f"[network].{key}: entry {item!r} has no "
                                  f"`host`")
                continue
            problems = _validate_container_host_pattern(item.get("host"))
            if problems:
                out_errors.extend(f"[network].{key}: {p}" for p in problems)
                continue
            host = item["host"].strip()
            out_hosts.append(host)
            if not isinstance(item.get("reason"), str) or not item["reason"].strip():
                out_errors.append(  # V14
                    f"[network].{key}: {host!r} has no `reason`; {bypass_clause}")
        return out_hosts, out_errors

    internal_hosts, internal_errors = _validate_host_reason_array(
        "internal",
        "it is a bypass of the internal-destination drop and carries one "
        "like [[network.allow]] does")
    errors.extend(internal_errors)

    splice_hosts, splice_errors = _validate_host_reason_array(
        "splice",
        "it exempts a host from inspection and carries one like "
        "[[network.allow]] does")
    errors.extend(splice_errors)
    for host in splice_hosts:
        # V12: dead-entry check. Splice only excepts from the allowlist -- a
        # policy entry already allowlists its own host (V1), so unlike
        # `internal` below this does not also check policy_hosts: exempting a
        # host from inspection that a policy entry intends to inspect is a
        # contradiction, not redundancy.
        if not any(_container_patterns_overlap(host, pattern) for pattern in hosts):
            errors.append(
                f"[network].splice: {host!r} matches no allowlisted name -- "
                f"nothing in .hosts covers it, so the entry exempts a host "
                f"the workload is refused before the exemption is reached. "
                f"Add it to .hosts, or drop this entry")

    # --- [[network.credential]] -- shape (feeds V7/V10) ---
    raw_credentials = net.get("credential", [])
    credentials: list[ContainerCredential] = []
    if not isinstance(raw_credentials, list):
        errors.append(
            f"[network].credential must be an array of "
            f"[[network.credential]] tables, got "
            f"{type(raw_credentials).__name__}")
        raw_credentials = []
    seen_cred_names: set[str] = set()
    seen_envs: set[str] = set()
    for item in raw_credentials:
        if not isinstance(item, dict):
            errors.append(f"[network].credential entries are tables with "
                          f"`name`, `placeholder` and `env`, got {item!r}")
            continue
        values = {}
        for key in ("name", "placeholder", "env"):
            value = item.get(key)
            if not isinstance(value, str) or not value.strip():
                errors.append(
                    f"[network].credential: entry {item!r} has no `{key}`; a "
                    f"block carries all three -- `name` selects the sealed "
                    f"material, `placeholder` is the fiction the container "
                    f"holds in its place, and `env` is the variable it is "
                    f"seeded into")
                values = {}
                break
            values[key] = value.strip()
        if not values:
            continue
        name, placeholder, env = values["name"], values["placeholder"], values["env"]
        if env in VM_RESERVED_GUEST_ENV:  # V10
            errors.append(
                f"[network].credential: {name!r} has `env` = {env!r}, which "
                f"is one of the CA trust-store variables workloadctl may seed "
                f"this container with. Choose another name")
            continue
        if env in seen_envs:
            errors.append(
                f"[network].credential: `env` = {env!r} is used by two "
                f"credential blocks, so one placeholder overwrites the other "
                f"and one credential's host answers 401 for a reason nothing "
                f"here reports")
            continue
        seen_envs.add(env)
        if name in seen_cred_names:
            errors.append(
                f"[network].credential: {name!r} is declared twice. A policy "
                f"entry selects a credential by name, so two blocks sharing "
                f"one make the selector ambiguous")
            continue
        seen_cred_names.add(name)
        auth_header = item.get("auth_header")
        auth_header = auth_header.strip() if isinstance(auth_header, str) and auth_header.strip() else None
        auth_format = item.get("auth_format")
        auth_format = auth_format.strip() if isinstance(auth_format, str) and auth_format.strip() else None
        credentials.append(ContainerCredential(
            name=name, placeholder=placeholder, env=env,
            auth_header=auth_header, auth_format=auth_format))
    credential_names = {c.name for c in credentials}

    # --- [[network.policy]] -- shape + V1-V11 ---
    raw_policy = net.get("policy", [])
    policy_entries: list[ContainerPolicyEntry] = []
    if not isinstance(raw_policy, list):
        errors.append(
            f"[network].policy must be an array of [[network.policy]] "
            f"tables, got {type(raw_policy).__name__}")
        raw_policy = []
    for item in raw_policy:
        if not isinstance(item, dict):
            errors.append(f"[network].policy entries are tables with `host` "
                          f"and optional `methods`/`paths`/`credential`, got "
                          f"{item!r}")
            continue
        if "host" not in item:
            errors.append(f"[network].policy: entry {item!r} has no `host`")
            continue
        problems = _validate_container_host_pattern(item.get("host"))
        if problems:
            errors.extend(f"[network].policy: {p}" for p in problems)
            continue
        host = item["host"].strip()

        methods: tuple | None = None
        if "methods" in item:
            value = item["methods"]
            if not isinstance(value, list):
                errors.append(f"[network].policy: {host!r} `methods` must "
                              f"be an array of HTTP method names, got "
                              f"{type(value).__name__}")
                methods = ()
            else:
                out = []
                for token in value:
                    if not isinstance(token, str) or token != token.strip() \
                            or any(c.isspace() for c in token):
                        errors.append(
                            f"[network].policy: {host!r} `methods` names "
                            f"{token!r}, which is not a usable HTTP method "
                            f"token")
                        continue
                    name = token.upper()
                    if name in VM_POLICY_METHODS_REFUSED:  # V5
                        errors.append(
                            f"[network].policy: {host!r} names the method "
                            f"{token!r}, which this inspector never sees -- "
                            f"{VM_POLICY_METHODS_REFUSED[name]}")
                        continue
                    if name not in VM_POLICY_METHODS:  # V5
                        errors.append(
                            f"[network].policy: {host!r} names {token!r}, "
                            f"which is not a registered HTTP method")
                        continue
                    out.append(name)
                if not out and value:
                    pass  # per-token errors already reported above
                elif not out:
                    errors.append(
                        f"[network].policy: {host!r} has an empty `methods` "
                        f"list, which permits no method at all. Omit the key "
                        f"to mean any method")
                methods = tuple(out)

        paths: tuple | None = None
        if "paths" in item:
            value = item["paths"]
            if not isinstance(value, list):
                errors.append(f"[network].policy: {host!r} `paths` must be "
                              f"an array of path patterns, got "
                              f"{type(value).__name__}")
                paths = ()
            else:
                out = []
                for pattern in value:
                    if not isinstance(pattern, str) or not pattern.strip():
                        errors.append(f"[network].policy: {host!r} `paths` "
                                      f"entries must be non-empty strings, "
                                      f"got {pattern!r}")
                        continue
                    if not pattern.startswith("/") or "?" in pattern or "#" in pattern:
                        errors.append(  # V6
                            f"[network].policy: {host!r} path {pattern!r} "
                            f"must start with '/' and carry no query or "
                            f"fragment -- `paths` matches the path alone")
                        continue
                    out.append(pattern)
                if not value:
                    errors.append(
                        f"[network].policy: {host!r} has an empty `paths` "
                        f"list, which permits no path at all. Omit the key "
                        f"to mean any path")
                paths = tuple(out)

        credential = None
        if "credential" in item:
            value = item.get("credential")
            if not isinstance(value, str) or not value.strip():
                errors.append(f"[network].policy: {host!r} `credential` "
                              f"must be the name of a [[network.credential]] "
                              f"block, got {value!r}")
            else:
                credential = value.strip()
                if credential not in credential_names:  # V7
                    errors.append(
                        f"[network].policy: {host!r} selects credential "
                        f"{credential!r}, which no [[network.credential]] "
                        f"block declares")
                if credential and "*" in host:  # V8
                    errors.append(
                        f"[network].policy: {host!r} selects credential "
                        f"{credential!r}, but a credential is attached per "
                        f"exact host -- the broker's table has no patterns, "
                        f"so every request matching this wildcard would be "
                        f"authorised here and refused there. Name the exact "
                        f"host this credential belongs to")

        policy_entries.append(ContainerPolicyEntry(
            host=host, methods=methods, paths=paths, credential=credential))

    # A credential nothing selects.
    for cred in credentials:
        if not any(e.credential == cred.name for e in policy_entries):
            errors.append(
                f"[network].credential: {cred.name!r} is declared but no "
                f"[[network.policy]] entry selects it, so it is sealed, "
                f"loaded and attached to nothing")

    policy_hosts = [e.host for e in policy_entries]

    for host in internal_hosts:
        # V12, deferred until policy_hosts exists: a name in `policy` need
        # not also appear in `hosts` (V1), so an `internal` entry for such a
        # name is live even though `hosts` alone does not cover it.
        if not any(_container_patterns_overlap(host, pattern) for pattern in hosts) \
                and not any(_container_patterns_overlap(host, pattern) for pattern in policy_hosts):
            errors.append(
                f"[network].internal: {host!r} is on no list -- nothing in "
                f".hosts allowlists it and no .policy entry names it, so the "
                f"entry excepts a destination the workload is refused before "
                f"the exception is reached. Add it to .hosts, or drop this "
                f"entry")

    if policy_entries:
        # V9: tls = "splice" plus any policy entry.
        explicit_tls = container_tls_mode(net)
        if explicit_tls == "splice":
            errors.append(
                "[network].policy with tls = 'splice' -- a spliced "
                "connection is never decrypted, so there is no request for "
                "`methods` and `paths` to be applied to and the entries "
                "would be silently inert. Drop tls = 'splice' (inspect is "
                "computed automatically once a policy entry exists), or "
                "drop the policy entries and keep the name allowlist in "
                ".hosts")

        # V3: where more than one entry matches a host by pattern, every one
        # of those entries must state both `methods` and `paths`.
        for i, entry in enumerate(policy_entries):
            siblings = [o for j, o in enumerate(policy_entries)
                       if j != i and _container_patterns_overlap(entry.host, o.host)]
            if not siblings:
                continue
            missing = [k for k, v in (("methods", entry.methods),
                                      ("paths", entry.paths)) if v is None]
            if missing:
                errors.append(
                    f"[network].policy: {entry.host!r} shares a host with "
                    f"{siblings[0].host!r} and omits "
                    f"{' and '.join(f'`{k}`' for k in missing)}. Where "
                    f"entries overlap, an omitted key means ANY -- state "
                    f"both keys on every overlapping entry")

        # V4: apex trap. A wildcard entry beneath an allowlisted apex leaves
        # the apex allowlisted and inspected with no rules applied.
        for apex in hosts:
            wildcard = f"*.{apex}"
            if not any(e.host.strip().lower() == wildcard.lower() for e in policy_entries):
                continue
            if any(vm_hostname_match(apex, (e.host,)) for e in policy_entries):
                continue
            errors.append(
                f"[network].policy: {wildcard!r} does not cover the apex "
                f"{apex!r}, which .hosts also allowlists -- patterns are "
                f"fnmatch, not DNS suffix matching, so the apex is "
                f"allowlisted and inspected with NO method or path rules "
                f"applied. Add an entry for {apex!r} too, or drop it from "
                f".hosts")

    # --- The `tls` scalar itself, and its `tls_reason` interlock ---
    #
    # Both of these are rules the VM side has and the first port of this
    # function did not, which is a shape worth naming: a value that is only
    # ever COMPUTED needs no domain check, and `tls` is computed for almost
    # every workload -- so the branch where an operator writes it by hand was
    # the one nothing constrained. An unrecognised literal is the worse of the
    # two. It is not merely accepted: container_effective_tls_mode() returns it
    # verbatim, so `tls = "inspct"` is an effective mode of "inspct", which is
    # neither "inspect" (so V16 never asks for ca_delivery) nor "splice" (so
    # V18 never fires), and the workload validates clean, starts clean, and
    # runs with a policy naming a mode the inspector does not implement.
    explicit_tls = container_tls_mode(net)
    if explicit_tls is not None and explicit_tls not in ("inspect", "splice"):
        errors.append(
            f"[network].tls must be 'inspect' or 'splice', got "
            f"{explicit_tls!r}. It is normally omitted -- the mode is computed "
            f"from whether any [[network.policy]] entry is present")

    tls_reason = container_tls_reason(net)
    if explicit_tls == "splice" and tls_reason is None:
        # Same rule as the VM's, for the same reason: this is the widest bypass
        # in the schema (every host, not a named one), and every narrower one
        # -- allow, internal, splice entries -- has carried a written reason
        # since it existed.
        errors.append(
            "[network].tls = 'splice' requires tls_reason. Writing it "
            "explicitly gives up per-request policy on EVERY host, which is "
            "wider than any [[network.splice]] entry; the person deciding "
            "months from now whether the bypass is still needed is not the one "
            "opening it. (Reaching splice by simply having no policy entries "
            "needs no reason -- nothing narrower was given up.)")
    if tls_reason is not None and explicit_tls != "splice":
        errors.append(
            "[network].tls_reason is set but tls = 'splice' is not written "
            "explicitly -- a reason recording a bypass that was never chosen "
            "sends a reviewer looking for an exposure that is not there")

    # V16/V18: the interlock between the computed tls mode and ca_delivery.
    effective_tls = container_effective_tls_mode(net)
    ca_delivery = container_ca_delivery(net)
    ca_mount_path = container_ca_mount_path(net)
    is_triggered = bool(hosts or policy_entries or net.get("allow"))
    if is_triggered and effective_tls == "inspect":
        if ca_delivery is None:  # V16
            errors.append(
                "[network]: this workload's effective tls mode is 'inspect' "
                "(a policy entry is present, or tls = 'inspect' was written "
                "explicitly), which needs a trust-delivery route -- "
                "ca_delivery is required. Set it to 'env', 'mount', or "
                "'image'")
        elif ca_delivery not in ("env", "mount", "image"):
            errors.append(
                f"[network].ca_delivery must be one of 'env', 'mount', "
                f"'image', got {ca_delivery!r}")
        elif ca_delivery == "mount" and not ca_mount_path:
            errors.append(
                "[network].ca_delivery = 'mount' requires ca_mount_path -- "
                "the in-container path the CA bundle is mounted at")
        # ca_delivery = "image" asserts the image was built trusting this
        # workload's CA, which can only be true of a bundle with its own
        # Containerfile (R9) -- but this function sees only [network], not
        # the bundle directory, so that check belongs to whichever caller
        # loads the whole workload (a TODO for P1-2's caller, not a gap in
        # this function's contract).
    if ca_mount_path and ca_delivery != "mount":
        errors.append(
            "[network].ca_mount_path is set but ca_delivery is not "
            "'mount' -- the path is only meaningful when workloadctl is "
            "the one bind-mounting the bundle")

    for host in splice_hosts:
        # V18: a per-host splice entry when the whole workload is already on
        # rung 2 (splice) exempts nothing, and V14 just made the operator
        # write a `reason` for a hole they did not open.
        if effective_tls == "splice":
            errors.append(
                f"[network].splice: {host!r} is redundant -- this "
                f"workload's effective tls mode is already 'splice', so "
                f"every host is spliced and this entry exempts nothing. "
                f"Drop it, or add a [[network.policy]] entry to move the "
                f"workload to rung 3 first")

    return errors


# --- Container egress: nft element lifecycle (P1-7/P1-8) ---
#
# The low-level uid-keyed nft builders (element commands for the DNAT maps,
# the internal-destination exemptions, the cgroup exemptions) live in
# lib/vm.py and take nothing but a uid and already-resolved addresses -- no
# VM-specific state -- so they are reused verbatim for containers (imported
# directly by libexec/workload-container-filter and
# libexec/workload-container-inspect). What differs, and what lives here, is
# resolving and shaping the CONTAINER schema's own entry types
# (ContainerAllowEntry keeps `host`/`address`/`port` apart, where VmAllowEntry
# packs them into one 'addr:port' string) into the inputs those builders take.

def container_allow_resolve(entry: ContainerAllowEntry) -> list:
    """Resolve one [[network.allow]] entry to concrete addresses.

    Mirrors vm_allow_resolve (lib/vm.py), adapted to ContainerAllowEntry's
    separate `address`/`host` fields. An address entry is returned as-is; a
    host entry is resolved here, once, at arm time. Not tolerant: an
    unresolvable name must arm nothing, and arming nothing silently is worse
    than failing loudly -- the workload would otherwise hang against the
    default-deny... except containers have none (R3), so here it would simply
    reach nothing on that destination with no message saying why.
    """
    import ipaddress
    import socket
    if entry.address is not None:
        return [ipaddress.ip_address(entry.address)]
    try:
        infos = socket.getaddrinfo(entry.host, None, type=socket.SOCK_STREAM)
    except OSError as exc:
        raise ValueError(
            f"[[network.allow]] names {entry.host!r}, which does not resolve "
            f"on this host ({exc}). It is resolved once at arm time, so an "
            f"unresolvable name arms nothing and the workload cannot reach "
            f"it") from None
    seen = []
    for info in infos:
        addr = ipaddress.ip_address(info[4][0])
        if addr not in seen:
            seen.append(addr)
    return seen


def container_allow_resolved(allow: list) -> list:
    """[(ContainerAllowEntry, [addr...])] for every [[network.allow]] entry,
    resolved once. Mirrors vm_allow_resolved."""
    return [(entry, container_allow_resolve(entry)) for entry in allow]


def container_filter_elements(uid: int, allow: list, resolved=None) -> dict:
    """Map set name -> element expressions for one container workload.

    Mirrors vm_filter_elements (lib/vm.py), but built from
    ContainerAllowEntry rather than VmAllowEntry. Reuses the VM module's set
    names and reserved-range check (NFT_SET_FILTERED/ALLOW4/ALLOW6,
    vm_allow_reserved_reason): both substrates share the one filter table
    (D3), so a container's would-be element in another workload's listener
    range is refused by the identical rule a VM's is.
    """
    from vm import NFT_SET_ALLOW4, NFT_SET_ALLOW6, NFT_SET_FILTERED, vm_allow_reserved_reason
    if resolved is None:
        resolved = container_allow_resolved(allow)
    elements: dict[str, list[str]] = {NFT_SET_FILTERED: [str(uid)]}
    v4: list[str] = []
    v6: list[str] = []
    for entry, addresses in resolved:
        for addr in addresses:
            reserved = vm_allow_reserved_reason(addr)
            if reserved:
                where = f"{entry.host!r} resolves there -- " if entry.host else ""
                raise ValueError(f"[network].allow: {where}{reserved}")
            (v6 if addr.version == 6 else v4).append(
                f"{uid} . {addr} . {entry.port}")
    if v4:
        elements[NFT_SET_ALLOW4] = v4
    if v6:
        elements[NFT_SET_ALLOW6] = v6
    return elements


def container_filter_commands(uid: int, allow: list, action: str, resolved=None) -> list:
    """argv lists that arm ('add') or disarm ('delete') one container
    workload's allowlist elements. Mirrors vm_filter_commands."""
    from vm import NFT_BIN, NFT_TABLE
    if action not in ("add", "delete"):
        raise ValueError(f"action must be 'add' or 'delete', got {action!r}")
    commands = []
    for set_name, entries in container_filter_elements(uid, allow, resolved).items():
        commands.append([NFT_BIN, action, "element", *NFT_TABLE.split(), set_name,
                         "{ " + ", ".join(entries) + " }"])
    return commands


def container_internal_resolve(host: str) -> list:
    """Resolve one [[network.internal]] host, or raise ValueError naming it.
    Mirrors vm_internal_resolve. Fatal by design (see that function and
    workload-vm-inspect's internal_failure): an exemption armed for the wrong
    address, or not armed at all, leaves the host refused by the drop the
    entry existed to except.
    """
    import ipaddress
    import socket
    try:
        infos = socket.getaddrinfo(host, None, type=socket.SOCK_STREAM)
    except OSError as exc:
        raise ValueError(
            f"[[network.internal]] names {host!r}, which does not resolve on "
            f"this host ({exc}). The exemption is armed per ADDRESS, so an "
            f"unresolvable name arms nothing and the host stays refused by "
            f"the internal-destination drop the entry existed to except") from None
    seen = []
    for info in infos:
        addr = ipaddress.ip_address(info[4][0])
        if addr not in seen:
            seen.append(addr)
    return seen


def container_inspect_policy(net: dict) -> dict:
    """The inspector's policy document for one container workload.

    Same JSON shape as vm_inspect_policy (lib/vm.py) -- D6: the listener
    binary (workload-vm-inspect-listener) does not change between substrates,
    so whichever wrote the file, it reads the same keys. `http2` is always
    empty: [[network.http2]] is deferred for containers (§5 of the build
    spec). `tls` is the EFFECTIVE mode (container_effective_tls_mode), not
    the literal key, since the container schema computes it per the
    three-rung ladder rather than defaulting it the way the VM schema does.
    """
    return {
        "tls": container_effective_tls_mode(net),
        "hosts": container_allowed_hosts(net),
        "internal": [e.host for e in container_internal_entries(net)],
        "splice": [e.host for e in container_splice_entries(net)],
        "http2": [],
        "policy": [
            {"host": e.host,
             "methods": None if e.methods is None else list(e.methods),
             "paths": None if e.paths is None else list(e.paths),
             **({"credential": e.credential} if e.credential else {})}
            for e in container_policy_entries(net)],
    }


def container_inspect_policy_text(net: dict) -> str:
    """The policy document as the exact bytes that land on disk. Mirrors
    vm_inspect_policy_text -- same formatting, so a future drift/digest
    comparison cannot disagree with itself over which substrate rendered the
    file."""
    import json
    return json.dumps(container_inspect_policy(net), indent=2, sort_keys=True) + "\n"


# --- Per-workload SELinux identifiers ---
#
# Each workload that ships extra rights gets its own name-keyed type instead of
# widening the shared container_t: a CIL module `wl_<name>` defining the process
# domain `wl_<name>.process`. The CLI (which loads the policy) and the generator
# (which labels the container) both derive identifiers through these functions
# so they can't drift. See llms.txt "SELinux confinement" for the rationale.
#
# hyphen->underscore is injective: NAME_PATTERN forbids underscores, so two
# distinct workload names can never collide on the same type.

def selinux_module_name(name: str) -> str:
    """SELinux/CIL module (block) name for a workload, e.g. 'wl_wayfire_bob'."""
    return "wl_" + name.replace("-", "_")


def selinux_type_name(name: str) -> str:
    """SELinux process type for a workload, e.g. 'wl_wayfire_bob.process'.

    Passed to `podman --security-opt label=type:`.
    """
    return selinux_module_name(name) + ".process"


# --- Volume path expansion ---

def _safe_anchor_subpath(sub: str) -> str:
    """Reject traversal/absolute escapes from a workload-relative anchor."""
    if sub.startswith("/") or ".." in Path(sub).parts:
        raise ValueError(f"unsafe anchored volume subpath: {sub!r}")
    return sub


def _expand_anchor(host: str, home_dir: str) -> str:
    """Resolve a workload-relative volume anchor to an absolute host path.

    home_dir is the workload STATE dir (= $HOME). The DATA dir is its sibling.
      data/sub  (sugar ./sub)  -> <root>/data/sub        (precious)
      state/sub (sugar @/sub)  -> <root>/state/volumes/sub (reconstructible)
    Anything else is returned unchanged.
    """
    data_root = str(Path(home_dir).parent / DATA_SUBDIR)
    state_vol_root = home_dir + "/volumes"
    # ./ and @/ are sugar for the canonical data/ and state/ prefixes. An empty
    # subpath (e.g. "./" or bare "data") resolves to the anchor root itself.
    for prefix, root in (("./", data_root), ("@/", state_vol_root),
                         ("data/", data_root), ("state/", state_vol_root)):
        if host.startswith(prefix):
            sub = _safe_anchor_subpath(host[len(prefix):])
            return root + "/" + sub if sub else root
    if host == "data":
        return data_root
    if host == "state":
        return state_vol_root
    return host


def expand_volume_path(vol_spec: str, home_dir: str) -> str:
    """Expand a workload-relative anchor in a volume spec's host path.

    Args:
        vol_spec: "host:guest[:opts]" — host may use ./ @/ data/ state/ anchors.
        home_dir: the workload STATE dir (= $HOME); data/ is its sibling.

    Returns the spec with the host path made absolute, original arity preserved.
    """
    host, guest, opts = parse_volume_spec(vol_spec)
    host = _expand_anchor(host, home_dir)
    ncolons = vol_spec.count(':')
    if ncolons == 0:
        return host
    if ncolons == 1:
        return f"{host}:{guest}"
    return f"{host}:{guest}:{opts}"


# --- Instance token expansion ---

# ${WORKLOAD_*} tokens usable in workload.toml values that must name the
# instance. Deliberately the same vocabulary provisioning.host_setup_env()
# exports to [host] setup scripts, so a bundle spells its own identity one way
# whether it's doing so from TOML or from shell.
WORKLOAD_TOKEN_PATTERN = re.compile(r'\$\{(WORKLOAD_[A-Z_]+)\}')


def workload_tokens(name: str) -> dict:
    """The ${WORKLOAD_*} token table for one instance."""
    return {
        "WORKLOAD_NAME": name,
        "WORKLOAD_INSTANCE_DIR": str(workload_config_dir() / name),
        "WORKLOAD_ROOT_DIR": str(workload_root_dir(name)),
        "WORKLOAD_STATE_DIR": str(workload_state_dir(name)),
        "WORKLOAD_DATA_DIR": str(workload_data_dir(name)),
    }


# Derived from the table itself so the two can't drift; the instance name is
# irrelevant to the key set.
WORKLOAD_TOKEN_NAMES = frozenset(workload_tokens("_"))


def expand_workload_tokens(value: str, name: str) -> str:
    """Expand ${WORKLOAD_*} tokens in a config value against instance `name`.

    Exists because a bundle can be instantiated under a different name
    (`init --as`), so any absolute path a TOML hardcodes for *itself* is wrong
    for every instance but the first. The alternative — writing
    /etc/workloads.d/<bundle>/... literally — silently points at a workload
    that doesn't exist.

    Unknown WORKLOAD_ tokens raise: a typo left to pass through would reach
    podman verbatim as a path that can never resolve, and failing at generate
    time with the token named is far easier to diagnose than a container that
    won't start.
    """
    tokens = workload_tokens(name)

    def sub(m):
        key = m.group(1)
        if key not in tokens:
            raise ValueError(
                f"unknown token ${{{key}}} (known: {', '.join(sorted(tokens))})")
        return tokens[key]

    return WORKLOAD_TOKEN_PATTERN.sub(sub, value)


# --- Quoting ---

def dq(s: str) -> str:
    """Quote a string as a LITERAL token for a systemd Exec* command line.

    Use for all tokens: paths, image names, command args, container names, env
    keys, and plain env VALUES.

    systemd applies two expansions to Exec directives that shell-style quoting
    does NOT suppress, so a bare double-quote is not enough:

      * `%` specifiers (`%i`, `%H`, …) are expanded at unit load, before quote
        parsing — a literal `%` must be written `%%`.
      * `$VAR` / `${VAR}` environment expansion runs on each argument *after*
        the command line is split and quotes are removed — so neither single nor
        double quotes stop it; a literal `$` must be written `$$`.

    (This is why single-quoting env values with shlex.quote was wrong: systemd
    still expands `$` inside them, and shlex's `'"'"'` escaping for an embedded
    single quote is shell syntax, not systemd's.)

    Backslash and double-quote are escaped for the surrounding double quotes;
    `$` and `%` are doubled to defeat the two expansions above. A single quote
    needs no escaping inside double quotes.
    """
    return (
        '"'
        + s.replace('\\', '\\\\')
           .replace('"', '\\"')
           .replace('$', '$$')
           .replace('%', '%%')
        + '"'
    )


def uq(s: str) -> str:
    """Quote a string as a LITERAL value for a NON-Exec systemd unit setting
    (RequiresMountsFor=, ReadWritePaths=, ...).

    Differs from dq() in exactly one way, and the difference matters: `$` /
    `${VAR}` expansion runs only on Exec command lines, so a `$` in an ordinary
    setting is *already* literal and doubling it would corrupt the value. `%`
    specifiers are expanded at unit load for every setting, so a literal `%`
    still has to be written `%%`.
    """
    return (
        '"'
        + s.replace('\\', '\\\\')
           .replace('"', '\\"')
           .replace('%', '%%')
        + '"'
    )
